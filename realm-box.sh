}

show_logs() {
  require_cmds journalctl
  load_mode
  echo
  echo "按 Ctrl+C 退出日志查看。"
  if [ "$MODE" = "realm" ]; then
    journalctl -u realm.service -f --no-hostname -o cat
  else
    journalctl -u sing-box-relay.service -f --no-hostname -o cat
  fi
}

show_status() {
  require_cmds systemctl ip uname hostname awk

  load_mode

  v4="$(get_primary_ipv4)"
  v6="$(get_primary_ipv6)"

  echo
  echo "==================== 状态 ===================="
  echo "系统：$(os_pretty)"
  echo "主机：$(hostname)"
  echo "内核：$(uname -r)"
  echo "出口 IPv4：$v4"
  echo "出口 IPv6：$v6"
  echo "当前模式：$MODE"
  echo
  echo "Realm 二进制：$BIN_REALM $( [ -x "$BIN_REALM" ] && echo "(ok)" || echo "(missing)" )"
  echo "Realm 配置：$CFG_REALM $( [ -f "$CFG_REALM" ] && echo "(ok)" || echo "(missing)" )"
  echo "Realm 服务：realm.service"
  if svc_exists_realm; then
    systemctl --no-pager -l status realm.service || true
  else
    echo "realm.service 未安装"
  fi

  echo
  echo "Sing-box 二进制：$BIN_SBOX $( [ -x "$BIN_SBOX" ] && echo "(ok)" || echo "(missing)" )"
  echo "Sing-box 配置：$CFG_SBOX $( [ -f "$CFG_SBOX" ] && echo "(ok)" || echo "(missing)" )"
  echo "Sing-box 服务：sing-box-relay.service"
  if svc_exists_sbox; then
    systemctl --no-pager -l status sing-box-relay.service || true
  else
    echo "sing-box-relay.service 未安装"
  fi

  echo
  echo "==================== 转发规则 ===================="
  if [ -s "$EP_DB" ]; then
    nl -ba "$EP_DB" | sed 's/^/  /'
  else
    echo "  (空)"
  fi
  echo "=================================================="
}

tcp_connect_test() {
  host="$1"
  port="$2"
  timeout_s="${3:-3}"
  if cmd_exists timeout; then
    timeout "$timeout_s" bash -c "cat </dev/null >/dev/tcp/${host}/${port}" >/dev/null 2>&1 || return 1
  else
    bash -c "cat </dev/null >/dev/tcp/${host}/${port}" >/dev/null 2>&1 || return 1
  fi
}

link_test() {
  require_cmds ip getent awk sed head

  ensure_dirs
  if [ ! -s "$EP_DB" ]; then
    err "当前没有任何转发规则，无法测试。"
    return 1
  fi

  echo
  echo "将对每条规则进行："
  echo "1) 解析落地地址（如为域名）"
  echo "2) TCP 连通性探测（到 落地地址:落地端口）"
  echo "3) 本地端口占用情况提示"
  echo

  while IFS= read -r line || [ -n "${line:-}" ]; do
    case "$line" in
      ''|\#*) continue ;;
    esac

    lp="$(echo "$line" | awk '{print $1}')"
    rh="$(echo "$line" | awk '{print $2}')"
    rp="$(echo "$line" | awk '{print $3}')"

    echo "---- 规则：[::]:${lp} -> ${rh}:${rp}"

    resolved=""
    case "$rh" in
      *:*|*.*.*.*)  # 粗略判断 IP
        resolved="$rh"
        echo "解析：IP（无需解析）"
        ;;
      *)
        resolved="$(getent ahosts "$rh" 2>/dev/null | awk '{print $1}' | head -n1 || true)"
        if [ -n "$resolved" ]; then
          echo "解析：$rh -> $resolved"
        else
          echo "解析：失败（DNS/hosts）"
        fi
        ;;
    esac

    if cmd_exists ss; then
      if ss -ltn 2>/dev/null | awk '{print $4}' | grep -Eq "(^|:)$lp\$"; then
        echo "本地端口：$lp 已有 TCP 监听（可能冲突，也可能是 relay）"
      else
        echo "本地端口：$lp 未发现 TCP 监听"
      fi
    else
      echo "本地端口：未检测（缺少 ss 命令）"
    fi

    ok="FAIL"
    if [ -n "$resolved" ]; then
      if tcp_connect_test "$resolved" "$rp" 3; then
        ok="OK"
      fi
    fi
    echo "落地 TCP 探测：$ok"
    echo
  done <"$EP_DB"
}

