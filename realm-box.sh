switch_mode() {
  need_root
  load_mode
  echo
  echo "当前模式：$MODE"
  echo "1) 切换为 Realm 模式"
  echo "2) 切换为 Sing-box 模式"
  printf "请选择 [1-2]: "
  read -r c
  case "${c:-}" in
    1)
      MODE="realm"
      save_mode
      say "已切换为 Realm 模式，请重启服务。"
      ;;
    2)
      MODE="sbox"
      save_mode
      say "已切换为 Sing-box 模式，请重启服务。"
      ;;
    *)
      warn "未更改模式。"
      ;;
  esac
}

